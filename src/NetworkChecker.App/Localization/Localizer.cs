    public static string Culture { get; private set; } = "ru-RU";
    public static string Translate(string text, string? culture)
    {
        if (culture?.StartsWith("en", StringComparison.OrdinalIgnoreCase) != true) return text;
        if (English.TryGetValue(text, out var translated)) return translated;
        var country = System.Text.RegularExpressions.Regex.Match(text,
            @"^([^()·]+) \(([A-Z]{2})\)(.*)$", System.Text.RegularExpressions.RegexOptions.CultureInvariant,
            TimeSpan.FromMilliseconds(100));
        if (country.Success && English.TryGetValue(country.Groups[1].Value, out var countryName))
            return $"{countryName} ({country.Groups[2].Value}){country.Groups[3].Value}";
        var separator = text.IndexOf(": ", StringComparison.Ordinal);
        if (separator > 0 && English.TryGetValue(text[..separator], out var category))
        {
            var tailText = text[(separator + 2)..];
            var translatedTail = Translate(tailText, culture);
            if (!string.Equals(tailText, translatedTail, StringComparison.Ordinal)) return $"{category}: {translatedTail}";
        }
        var egressCountry = System.Text.RegularExpressions.Regex.Match(text, @"^Страна выхода: (.+)\.$",
            System.Text.RegularExpressions.RegexOptions.CultureInvariant, TimeSpan.FromMilliseconds(100));
        if (egressCountry.Success) return $"Egress country: {Translate(egressCountry.Groups[1].Value, culture)}.";
        var geoSummary = System.Text.RegularExpressions.Regex.Match(text,
            @"^GeoIP определяет страну как (.+)\. Сайты могут использовать другие базы\. Часть сервисов предложит другой язык, другую версию сайта или попросит подтвердить номер\.$",
            System.Text.RegularExpressions.RegexOptions.CultureInvariant, TimeSpan.FromMilliseconds(100));
        if (geoSummary.Success)
            return $"GeoIP identifies the country as {Translate(geoSummary.Groups[1].Value, culture)}. Websites may use other databases. Some services may offer a different language or version, or request phone verification.";
        var languageCountry = System.Text.RegularExpressions.Regex.Match(text,
            @"^Язык системы — (.+), адрес — (.+)\. Такое сочетание встречается по множеству причин и не доказывает VPN\.$",
            System.Text.RegularExpressions.RegexOptions.CultureInvariant, TimeSpan.FromMilliseconds(100));
        if (languageCountry.Success)
            return $"System language: {languageCountry.Groups[1].Value}; IP country: {Translate(languageCountry.Groups[2].Value, culture)}. This combination has many possible causes and does not prove VPN use.";
        var factAddress = System.Text.RegularExpressions.Regex.Match(text, @"^(.+) · адрес из региона (.+)$",
            System.Text.RegularExpressions.RegexOptions.CultureInvariant, TimeSpan.FromMilliseconds(100));
        if (factAddress.Success) return $"{factAddress.Groups[1].Value} · address in region {Translate(factAddress.Groups[2].Value, culture)}";
        var latency = System.Text.RegularExpressions.Regex.Match(text, @"^Россия (.+) · мир (.+)$",
            System.Text.RegularExpressions.RegexOptions.CultureInvariant, TimeSpan.FromMilliseconds(100));
        if (latency.Success) return $"Russia {Translate(latency.Groups[1].Value, culture)} · world {Translate(latency.Groups[2].Value, culture)}";
        var measured = System.Text.RegularExpressions.Regex.Match(text, @"^(.+) Замер: (.+)\.$",
            System.Text.RegularExpressions.RegexOptions.CultureInvariant, TimeSpan.FromMilliseconds(100));
        if (measured.Success && English.TryGetValue(measured.Groups[1].Value, out var measuredPrefix))
            return $"{measuredPrefix} Measurement: {measured.Groups[2].Value}.";
        var overall = System.Text.RegularExpressions.Regex.Match(text, @"^(.+) · (\d+) проверок не отработали$",
            System.Text.RegularExpressions.RegexOptions.CultureInvariant, TimeSpan.FromMilliseconds(100));
        if (overall.Success && English.TryGetValue(overall.Groups[1].Value, out var overallPrefix))
            return $"{overallPrefix} · {overall.Groups[2].Value} checks failed";
        // Only known whole-string templates are translated. Unknown OS or third-party text
        // is retained verbatim, never sent to a network service or guessed.
        foreach (var (pattern, replacement) in DynamicTemplates)
        {
            if (pattern.IsMatch(text)) return pattern.Replace(text, replacement);
        }
        // Plain verdict explanations append an optional count of skipped/failed checks.
        var tail = System.Text.RegularExpressions.Regex.Match(text,
            @"^(.*) Правда, (\d+) проверок пропущены или не смогли отработать — часть картины неизвестна\.$",
            System.Text.RegularExpressions.RegexOptions.CultureInvariant, TimeSpan.FromMilliseconds(100));
        if (tail.Success && English.TryGetValue(tail.Groups[1].Value, out var prefix))
            return $"{prefix} {tail.Groups[2].Value} checks were skipped or failed; part of the picture is unknown.";
        return text;
    }

